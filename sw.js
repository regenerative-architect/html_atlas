/* =====================================================================
   Atlas service worker (generated by tools/atlas_build.py — edit
   tools/shared/sw.js instead). Only used when the atlas is served from
   https:// or http://localhost; pages opened as files never need it.

   What it does
   - Keeps the atlas usable offline: pages you open are kept in a local
     cache, and on install it saves every page unless your browser asks
     to save data (then you can save them later from the privacy panel).
   - Prefers fresh pages from the network, but gives up after a few
     seconds on a bad connection and shows the saved copy instead.
   - Never touches requests to other websites, and never sends data out.
   The cache name includes a content hash, so updates arrive automatically.
   ===================================================================== */
