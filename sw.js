const NETWORK_TIMEOUT_MS=3500;

function saveData(){try{return !!(self.navigator.connection&&self.navigator.connection.saveData)}catch(e){return false}}

async function cacheList(list,onProgress){
  const cache=await caches.open(CACHE);let done=0;
  for(const url of list){
    try{if(!(await cache.match(url))){const r=await fetch(url,{cache:'no-cache'});if(r.ok)await cache.put(url,r)}}catch(e){}
    done++;if(onProgress)onProgress(done,list.length);
  }
}
async function cachedPageCount(){
  const cache=await caches.open(CACHE);let n=0;
  for(const url of PAGES){if(await cache.match(url))n++}
  return n;
}

self.addEventListener('install',event=>{
  event.waitUntil((async()=>{
    const cache=await caches.open(CACHE);
    await cache.addAll(CORE);
    if(!saveData())await cacheList(PAGES);
    await self.skipWaiting();
  })());
});

self.addEventListener('activate',event=>{
  event.waitUntil((async()=>{
    for(const key of await caches.keys())if(key.startsWith('foster-navi-atlas')&&key!==CACHE)await caches.delete(key);
    await self.clients.claim();
  })());
});

function timeout(ms){return new Promise((_,reject)=>setTimeout(()=>reject(new Error('timeout')),ms))}

async function fromCache(req){
  const cache=await caches.open(CACHE);
  let hit=await cache.match(req,{ignoreSearch:true});
  if(!hit){const u=new URL(req.url);if(u.pathname.endsWith('/'))hit=await cache.match(u.pathname+'index.html')}
  return hit;
}

self.addEventListener('fetch',event=>{
  const req=event.request;
  if(req.method!=='GET')return;
  const url=new URL(req.url);
  if(url.origin!==self.location.origin)return; /* other websites: not ours to handle */
  const isPage=req.mode==='navigate'||(req.headers.get('accept')||'').includes('text/html');
  event.respondWith((async()=>{
    const cache=await caches.open(CACHE);
    if(isPage){
      /* Network first with a time limit, then the saved copy. */
      try{
        const res=await Promise.race([fetch(req),timeout(NETWORK_TIMEOUT_MS)]);
        if(res&&res.ok)cache.put(req,res.clone()).catch(()=>{});
        return res;
      }catch(e){
        const hit=await fromCache(req);
        if(hit)return hit;
        const home=await cache.match('./index.html');
        return home||new Response('<!doctype html><meta charset="utf-8"><title>Offline</title><p>You are offline and this page has not been saved yet. Reconnect and try again.</p>',{status:503,headers:{'Content-Type':'text/html; charset=utf-8'}});
      }
    }
    /* Everything else: answer from the cache at once, refresh in the background. */
    const hit=await fromCache(req);
    const refresh=fetch(req).then(res=>{if(res&&res.ok)cache.put(req,res.clone()).catch(()=>{});return res}).catch(()=>null);
    if(hit){event.waitUntil(refresh);return hit}
    const res=await refresh;
    return res||Response.error();
  })());
});

/* The privacy panel asks: how much is saved? save everything? remove it? */
self.addEventListener('message',event=>{
  const port=event.ports&&event.ports[0];if(!port||!event.data)return;
  const type=event.data.type;
  event.waitUntil((async()=>{
    if(type==='status'){port.postMessage({cached:await cachedPageCount(),total:PAGES.length});}
    else if(type==='cache-all'){
      await cacheList(PAGES,(done,total)=>port.postMessage({progress:true,cached:done,total}));
      port.postMessage({cached:await cachedPageCount(),total:PAGES.length});
    }
    else if(type==='clear'){
      const cache=await caches.open(CACHE);
      for(const url of PAGES)if(url!=='./index.html')await cache.delete(url);
      port.postMessage({cached:await cachedPageCount(),total:PAGES.length});
    }
  })());
});
